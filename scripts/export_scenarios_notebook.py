"""Regenerate databricks_scenarios.py (a Databricks notebook) from app/scenarios.py so the two never drift.

    python scripts/export_scenarios_notebook.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app.scenarios import rows_for_export  # noqa: E402

rows = rows_for_export()
data = ",\n".join("    " + json.dumps(r) for r in rows).replace("true", "True").replace("false", "False")
(ROOT / "databricks_scenarios.py").write_text(f'''# Databricks notebook source
# SYNTHETIC DEMO ONLY. Creates the live-status table the FastER backend reads in DATA_MODE=databricks.
# Generated by scripts/export_scenarios_notebook.py from app/scenarios.py.
# To change a surge: edit a row in the table with SQL (see the last cell) or edit scenarios.py and regenerate.
from pyspark.sql import functions as F
import re

dbutils.widgets.text("catalog", "workspace")
dbutils.widgets.text("schema", "faster")
catalog, schema = dbutils.widgets.get("catalog"), dbutils.widgets.get("schema")
assert all(re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", n) for n in (catalog, schema))
table = f"{{catalog}}.{{schema}}.gold_hospital_status_by_scenario"
spark.sql(f"CREATE SCHEMA IF NOT EXISTS {{catalog}}.{{schema}}")
# COMMAND ----------
rows = [
{data}
]
df = (spark.createDataFrame(rows)
      .withColumn("acuity", F.col("acuity").cast("int"))
      .withColumn("waiting_count", F.col("waiting_count").cast("bigint"))
      .withColumn("active_clinicians", F.col("active_clinicians").cast("bigint"))
      .withColumn("travel_minutes", F.col("travel_minutes").cast("double"))
      .withColumn("surge", F.col("surge").cast("boolean"))
      # Rows are read as a fresh synthetic snapshot; rerun this notebook to refresh the timestamp.
      .withColumn("observed_at", F.date_format(F.current_timestamp(), "yyyy-MM-dd'T'HH:mm:ss.SSSXXX"))
      .select("scenario", "hospital_id", "acuity", "waiting_count", "active_clinicians",
              "travel_minutes", "surge", "observed_at"))
df.write.mode("overwrite").format("delta").saveAsTable(table)
display(spark.table(table).orderBy("scenario", "hospital_id", "acuity"))
# COMMAND ----------
# Example: make Samaritan the surge hospital in the highway_accident scenario (uncomment to try).
# spark.sql(f"UPDATE {{table}} SET waiting_count = 14 WHERE scenario = 'highway_accident' AND hospital_id = 'SAM' AND acuity = 3")
# Permissions for the app's SQL warehouse identity: USE CATALOG, USE SCHEMA, SELECT on this table.
''')
print("wrote databricks_scenarios.py with", len(rows), "rows")
